async(page)=>{
  const base=new URL('./',page.url()).href,errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'?match=2026-11-22&section=overview');
  const frame=page.frameLocator('#report-frame');
  await frame.getByRole('tab',{name:'Team strength',exact:true}).waitFor({state:'visible'});
  const d=JSON.parse(await frame.locator('#match-data').textContent());
  if(d.meta.id!=='2026-11-22'||d.meta.category!=='phnt'||d.meta.recording_owner!=='PHNT'||d.meta.phnt_team!=='Blue')throw Error('Recording in wrong category');
  if(d.meta.result!=='2nd place'||d.meta.final_scores.Blue!==96||d.meta.final_scores.Red!==100||d.meta.final_scores.Green!==96)throw Error('Wrong verified result');
  if(d.summary.feed_frames!==31340||d.summary.feed_start_seconds!==370||d.summary.feed_end_seconds!==8204.75)throw Error('Incomplete or wrong-round extraction');
  if(d.clips.length||await frame.locator('#tab-clips').count()||await frame.locator('video[src]').count())throw Error('Video clips must stay offline');
  if(await page.getByLabel('Select match').locator('option').count()!==4)throw Error('Main PHNT catalog missing the new match');
  const activity=await frame.locator('#activity-chart rect').count();
  if(activity!==42)throw Error('Long recording collapsed into fixed activity bins');
  if(!(await frame.locator('#tickets-chart').textContent()).includes('130m'))throw Error('Ticket axis truncated');
  await page.screenshot({path:'qa/nov22-overview.png'});
  await frame.getByRole('tab',{name:'Team strength',exact:true}).click();
  const rings=await frame.locator('#strength-chart circle').count();
  if(rings!==112)throw Error('Expected 112 accepted samples strictly above 33');
  if(!(await frame.locator('#strength-chart').textContent()).includes('130m'))throw Error('Strength axis truncated');
  await frame.locator('[data-peak="Blue"]').click();
  await frame.locator('#evidence').evaluate(el=>el.decode());
  if(await frame.locator('#inspect-title').textContent()!=='Blue strength: 47')throw Error('Verified Blue peak lost');
  if(await frame.getByRole('button',{name:'Play hosted source excerpt'}).isVisible())throw Error('Removed clip control visible');
  await page.screenshot({path:'qa/nov22-strength-evidence.png'});
  await frame.getByRole('button',{name:'Close evidence'}).click();
  await frame.getByRole('tab',{name:'Feed exchanges',exact:true}).click();
  await frame.getByLabel('PHNT involved').uncheck();
  await frame.locator('#quality').selectOption('reviewed');
  if(await frame.locator('#event-rows tr').count()!==8)throw Error('Recording-specific reviews lost');
  const marcus=frame.locator('#event-rows tr').filter({hasText:'Marcus'});
  await marcus.getByRole('button').click();
  await frame.locator('#evidence').evaluate(el=>el.decode());
  const evidence=await frame.locator('#evidence').evaluate(el=>({width:el.naturalWidth,height:el.naturalHeight}));
  if(evidence.width!==900||evidence.height!==104)throw Error('Native row evidence missing');
  await page.screenshot({path:'qa/nov22-feed-evidence.png'});
  await frame.getByRole('button',{name:'Close evidence'}).click();
  await frame.getByRole('tab',{name:'Map observations',exact:true}).click();
  if(await frame.locator('#map-gallery figure').count()!==12)throw Error('Map snapshots missing');
  await frame.getByRole('tab',{name:'Data & coverage',exact:true}).click();
  const coverage=await frame.locator('#data').textContent();
  if(!coverage.includes('PHNT clan recording')||!coverage.includes('26 readable paired'))throw Error('Coverage/category not explained');
  await page.screenshot({path:'qa/nov22-coverage.png'});
  await page.getByRole('tab',{name:'Compare matches',exact:true}).click();
  if(await page.locator('#comparison-rows tr').count()!==4)throw Error('PHNT comparison missing match');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'qa/nov22-mobile.png'});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
  await page.setViewportSize({width:1440,height:1000});
  if(errors.length)throw Error(errors.join('\n'));
  return {category:d.meta.category,phnt:d.meta.phnt_team,accepted:d.summary.accepted_feed_entries,charted:d.summary.charted_events,strengthFlags:rings,evidence,hostedClips:d.clips.length,pageErrors:errors};
}
