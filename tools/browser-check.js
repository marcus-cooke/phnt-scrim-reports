async(page)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const origin=new URL(page.url()).origin;
  await page.goto(origin+'/?match=2026-10-25&section=strength');
  const report=()=>page.frameLocator('#report-frame');
  await report().getByRole('tab',{name:'Team strength',exact:true}).waitFor({state:'visible'});
  await report().locator('#strength-chart circle').first().waitFor({state:'visible'});
  const newer=JSON.parse(await report().locator('#match-data').textContent());
  if(newer.meta.phnt_team!=='Blue')throw Error('Incorrect new-match PHNT faction');
  if(newer.tickets.some(r=>r.video_seconds<300)||newer.events.some(r=>r.first_seen_seconds<300)||newer.strength.rows.some(r=>r.video_seconds<300))throw Error('Prior game tail leaked into report');
  const newRings=await report().locator('#strength-chart circle').count();
  if(newRings!==271)throw Error('New-match flags mismatch');
  await report().locator('[data-peak="Blue"]').click();
  await report().locator('#evidence').evaluate(el=>el.decode());
  const peak=await report().locator('#inspect-title').textContent();
  if(peak!=='Blue strength: 53')throw Error('New peak mismatch');
  await report().getByRole('button',{name:'Play hosted source excerpt'}).click();
  await report().locator('#source-video').evaluate(el=>new Promise((resolve,reject)=>{if(el.readyState>=1)return resolve();el.addEventListener('loadedmetadata',resolve,{once:true});el.addEventListener('error',()=>reject(Error(el.error?.message)),{once:true})}));
  const clip=await report().locator('#source-video').evaluate(el=>({duration:el.duration,ready:el.readyState,src:el.currentSrc}));
  if(clip.duration<9||clip.duration>11||!clip.src.includes('/clips/'))throw Error('Static excerpt playback mismatch');
  await report().getByRole('button',{name:'Close evidence'}).click();
  await page.screenshot({path:'qa/new-strength.png'});
  await page.getByLabel('Select match').selectOption('2026-10-24');
  await report().locator('#strength-chart circle').first().waitFor({state:'visible'});
  await page.waitForFunction(()=>document.getElementById('report-frame').contentDocument?.querySelector('#match-data')?.textContent.includes('"phnt_team":"Green"'));
  const older=JSON.parse(await report().locator('#match-data').textContent());
  if(older.meta.phnt_team!=='Green')throw Error('Incorrect old-match faction');
  const oldRings=await report().locator('#strength-chart circle').count();
  if(oldRings!==320)throw Error('Old flags mismatch');
  await report().getByRole('tab',{name:'Feed exchanges',exact:true}).click();
  await report().getByRole('searchbox',{name:'Search player or clan'}).fill('Xinssan');
  if(await report().locator('#event-rows tr').count()===0)throw Error('Feed search broken');
  await page.getByRole('tab',{name:'Compare matches',exact:true}).click();
  if(await page.locator('#comparison-rows tr').count()!==2)throw Error('Comparison missing a match');
  await page.screenshot({path:'qa/compare-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>innerWidth===390);
  await page.screenshot({path:'qa/compare-mobile.png'});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  if(overflow)throw Error('Mobile page overflow');
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('tab',{name:'Match report',exact:true}).click();
  await page.getByLabel('Select match').selectOption('2026-10-25');
  if(errors.length)throw Error(errors.join('\n'));
  return {newMatch:{phnt:newer.meta.phnt_team,rings:newRings,firstTicket:Math.min(...newer.tickets.map(r=>r.video_seconds))},oldMatch:{phnt:older.meta.phnt_team,rings:oldRings},staticClip:clip,comparisonRows:2,mobileOverflow:overflow,pageErrors:errors};
}
