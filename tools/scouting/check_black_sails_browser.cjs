const fs=require('fs');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
  const origin=process.argv[2]||'http://127.0.0.1:8027';
  const output=process.argv[3]||'analysis/black-sails-EaqOp1Fh7D0/qa';
  fs.mkdirSync(output,{recursive:true});
  const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? {executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE} : {})});
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  const errors=[],badResponses=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.url().startsWith(origin)&&r.status()>=400)badResponses.push([r.status(),r.url()])});
  const assert=(v,m)=>{if(!v)throw Error(m)};
  await page.goto(origin+'/');
  await page.getByRole('link',{name:'Opponent scouting',exact:false}).click();
  await page.locator('.finding').first().waitFor();await page.evaluate(()=>document.fonts.ready);
  assert(await page.locator('.finding').count()===11,'Missing scouting findings');
  assert((await page.locator('#result').textContent()).includes('100 / 98 / 99'),'Wrong result');
  await page.screenshot({path:output+'/briefing-desktop.png',fullPage:true});
  await page.getByLabel('Recorded side').selectOption('red');
  assert(await page.locator('.finding').count()===3,'Red coalition filter mismatch');
  await page.getByLabel('Finding type').selectOption('weakness');
  assert(await page.locator('.finding').count()===2,'Red weakness filter mismatch');
  await page.getByLabel('Recorded side').selectOption('green');
  assert(await page.locator('.finding').count()===1,'Green weakness filter mismatch');
  await page.reload();
  assert(await page.getByLabel('Recorded side').inputValue()==='green','Shared side filter lost');
  assert(await page.locator('.finding').count()===1,'Shared type filter lost');
  await page.getByLabel('Recorded side').selectOption('all');await page.getByLabel('Finding type').selectOption('all');
  await page.locator('[data-evidence="late-deficit"]').first().click();
  assert(await page.locator('#inspector').evaluate(e=>e.open),'Evidence dialog did not open');
  await page.locator('#evidence-image').evaluate(e=>e.decode());
  await page.getByRole('button',{name:'Play excerpt',exact:true}).click();
  assert(await page.locator('#evidence-image').evaluate(e=>e.hidden),'Excerpt mode should hide the screenshot');
  const clip=await page.locator('#evidence-video').evaluate(el=>new Promise((resolve,reject)=>{
    const done=()=>resolve({duration:el.duration,width:el.videoWidth,height:el.videoHeight});
    if(el.readyState>=1)return done();el.addEventListener('loadedmetadata',done,{once:true});el.addEventListener('error',()=>reject(Error(el.error?.message||'Video decode failed')),{once:true});
  }));
  assert(clip.duration>84&&clip.duration<86&&clip.width===1280,'Evidence excerpt mismatch');
  assert(page.url().includes('evidence=late-deficit'),'Evidence share link missing');
  await page.locator('#evidence-video').evaluate(async e=>{e.muted=true;await e.play()});
  await page.waitForFunction(()=>document.getElementById('evidence-video').currentTime>.5);
  await page.screenshot({path:output+'/evidence-desktop.png'});
  await page.keyboard.press('Escape');
  assert(!await page.locator('#inspector').evaluate(e=>e.open),'Escape did not close evidence');
  assert(!page.url().includes('evidence='),'Closed evidence persisted in URL');
  await page.getByRole('button',{name:'Match timeline',exact:true}).click();
  assert(await page.locator('#score-rows tr').count()===21,'Missing score anchors');
  assert(await page.locator('#score-chart circle').count()===63,'Missing score observations');
  await page.screenshot({path:output+'/timeline-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Evidence library',exact:true}).click();
  assert(await page.locator('.evidence-card').count()===20,'Evidence library should omit extra score-only anchors');
  await page.getByRole('button',{name:'Coverage & method',exact:true}).click();
  const dataResponse=await page.request.get(origin+'/scouting/data/scouting-report.json');
  const data=await dataResponse.json();assert(data.findings.length===11&&data.coverage.continuous_visual_watch===false,'Coverage export mismatch');
  await page.goto(origin+'/scouting/?view=timeline&team=green&evidence=result');
  await page.locator('#inspector[open]').waitFor();
  await page.locator('#evidence-image').evaluate(e=>e.decode());
  assert((await page.locator('#evidence-title').textContent()).includes('100–98–99'),'Direct evidence URL failed');
  await page.getByRole('button',{name:'Close evidence',exact:false}).click();
  assert(!await page.locator('#inspector').evaluate(e=>e.open),'Close button reopened the dialog');
  await page.getByRole('button',{name:'The briefing',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:output+'/briefing-mobile.png',fullPage:true});
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'Mobile briefing overflow');
  await page.getByRole('button',{name:'Match timeline',exact:true}).click();
  assert(!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'Mobile timeline page overflow');
  await page.locator('#score-rows [data-evidence="late-deficit"]').click();
  await page.locator('#evidence-image').evaluate(e=>e.decode());
  await page.screenshot({path:output+'/evidence-mobile.png'});
  assert(!await page.locator('#inspector').evaluate(e=>e.scrollWidth>e.clientWidth),'Mobile dialog overflow');
  assert(!errors.length,errors.join('\n'));assert(!badResponses.length,JSON.stringify(badResponses));
  const result={findings:data.findings.length,evidence:data.evidence.length,scoreAnchors:data.score_anchors.length,clip,desktopAndMobile:true,pageErrors:errors,badResponses};
  fs.writeFileSync(output+'/browser-results.json',JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
